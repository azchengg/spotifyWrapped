"""Generate seed.sql with fictional but realistic streaming data.

Usage: python3 generate_seed.py > seed.sql
Fixed random seed, so output is reproducible.
"""
import random
from datetime import date, datetime, timedelta

random.seed(42)

GENRES = ["pop", "hip-hop", "indie", "r&b", "electronic", "rock", "k-pop", "jazz"]

ARTISTS = [
    ("Luna Vale", "pop", "US"), ("The Paper Kites Club", "indie", "AU"),
    ("MC Drift", "hip-hop", "US"), ("Saffron", "r&b", "UK"),
    ("Neon Harbor", "electronic", "DE"), ("Static Bloom", "rock", "US"),
    ("STARLIGHT", "k-pop", "KR"), ("Miles Ember", "jazz", "US"),
    ("Coral Kids", "indie", "UK"), ("Yung Atlas", "hip-hop", "CA"),
    ("Velvet June", "r&b", "US"), ("Pixel Heart", "electronic", "JP"),
    ("Ruby Sky", "pop", "CA"), ("Gravel Road", "rock", "UK"),
    ("NOVA9", "k-pop", "KR"), ("Blue Note Trio", "jazz", "FR"),
    ("Honey Static", "pop", "SE"), ("Kairo", "hip-hop", "UK"),
    ("Moth & Moon", "indie", "US"), ("Daydream Arcade", "electronic", "US"),
]

WORDS = ["Midnight", "Golden", "Echo", "Summer", "Static", "Paper", "Velvet",
         "Neon", "Gravity", "Satellite", "Honey", "Ocean", "Ghost", "Wildfire",
         "Glass", "Silver", "Daydream", "Lights", "Heart", "Rain", "City",
         "Fever", "Signal", "Polaroid", "Orbit", "Mirror", "Sugar", "Thunder"]

COUNTRIES = ["US", "US", "US", "UK", "CA", "KR", "DE", "BR", "JP", "AU"]
DEVICES = ["phone"] * 6 + ["desktop"] * 2 + ["web", "speaker"]
SEASONS = ["winter", "spring", "summer", "fall"]


def season_of(d):
    return SEASONS[(d.month % 12) // 3]


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def title():
    n = random.choice([1, 2, 2, 3])
    return " ".join(random.sample(WORDS, n))


out = []
emit = out.append
emit("-- Generated by generate_seed.py. Do not edit by hand.")
emit("PRAGMA foreign_keys = ON;")
emit("BEGIN;")

# Artists
for i, (name, genre, country) in enumerate(ARTISTS, 1):
    emit(f"INSERT INTO artists VALUES ({i}, {q(name)}, {q(genre)}, {q(country)});")

# Albums and tracks
album_id = track_id = 0
tracks_by_artist = {}
track_meta = {}  # track_id -> (artist_id, duration_ms, release_date)
for artist_id in range(1, len(ARTISTS) + 1):
    tracks_by_artist[artist_id] = []
    for _ in range(random.randint(2, 4)):
        album_id += 1
        release = date(2018, 1, 1) + timedelta(days=random.randint(0, 3000))
        emit(f"INSERT INTO albums VALUES ({album_id}, {artist_id}, {q(title())}, '{release}');")
        for _ in range(random.randint(6, 12)):
            track_id += 1
            dur = random.randint(140_000, 300_000)
            explicit = 1 if random.random() < 0.25 else 0
            emit(f"INSERT INTO tracks VALUES ({track_id}, {album_id}, {q(title())}, {dur}, {explicit});")
            emit(f"INSERT INTO track_artists VALUES ({track_id}, {artist_id}, 'primary');")
            if random.random() < 0.12:
                feat = random.choice([a for a in range(1, len(ARTISTS) + 1) if a != artist_id])
                emit(f"INSERT INTO track_artists VALUES ({track_id}, {feat}, 'featured');")
            tracks_by_artist[artist_id].append(track_id)
            track_meta[track_id] = (artist_id, dur, release)

artists_by_genre = {}
for i, (_, genre, _) in enumerate(ARTISTS, 1):
    artists_by_genre.setdefault(genre, []).append(i)

# Users, each with a taste profile
NUM_USERS = 25
users = []
for uid in range(1, NUM_USERS + 1):
    username = f"{random.choice(WORDS).lower()}{random.choice(WORDS).lower()}{random.randint(1, 99)}"
    username = f"{username}_{uid}"
    plan = random.choices(["free", "premium", "student"], [4, 4, 2])[0]
    joined = date(2023, 1, 1) + timedelta(days=random.randint(0, 800))
    emit(f"INSERT INTO users VALUES ({uid}, {q(username)}, {q(random.choice(COUNTRIES))}, {q(plan)}, '{joined}');")
    fav_genres = random.sample(GENRES, 2)
    fav_artists = random.sample(range(1, len(ARTISTS) + 1), 3)
    users.append((uid, joined, fav_genres, fav_artists, random.uniform(0.5, 2.0)))

# Follows
for uid, joined, fav_genres, fav_artists, _ in users:
    followed = set(fav_artists) | set(random.sample(range(1, len(ARTISTS) + 1), random.randint(0, 3)))
    for a in sorted(followed):
        d = joined + timedelta(days=random.randint(0, 200))
        emit(f"INSERT INTO follows VALUES ({uid}, {a}, '{d}');")

# Plays: Jan 2025 through Oct 2026
START = datetime(2025, 1, 1)
END = datetime(2026, 10, 26)
play_id = 0
user_tracks = {}
for uid, joined, fav_genres, fav_artists, activity in users:
    # Each user has a seasonal genre (e.g. winter jazz, summer pop) and drifts
    # toward their second favourite genre over time.
    seasonal = {season: random.choice(GENRES) for season in SEASONS}
    obsessions = random.sample(list(track_meta), 4)
    pools = {}
    for season in SEASONS:
        for year in (2025, 2026):
            weights = []
            for t, (a, _, _) in track_meta.items():
                g = ARTISTS[a - 1][1]
                w = 1.0
                if g == fav_genres[0]:
                    w = 7.0 if year == 2025 else 3.0
                if g == fav_genres[1]:
                    w = 2.0 if year == 2025 else 8.0
                if g == seasonal[season]:
                    w *= 4.0
                if a in fav_artists:
                    w *= 2.5
                if t in obsessions:
                    w *= 12
                weights.append(w)
            pools[(season, year)] = (list(track_meta), weights)

    start = max(START, datetime.combine(joined, datetime.min.time()))
    day = start
    while day <= END:
        n = int(random.gauss(4, 2.5) * activity)
        if random.random() < 0.15:
            n = 0  # days off
        pool, wts = pools[(season_of(day), day.year)]
        for _ in range(max(n, 0)):
            t = random.choices(pool, wts)[0]
            a, dur, release = track_meta[t]
            hour = random.choices(range(24), [1,1,1,1,1,1,2,4,5,4,3,3,4,4,4,5,6,7,8,8,7,6,4,2])[0]
            played_at = day.replace(hour=hour, minute=random.randint(0, 59), second=random.randint(0, 59))
            if played_at.date() < release:
                continue
            skipped = 1 if random.random() < 0.18 else 0
            ms = random.randint(3_000, 30_000) if skipped else random.randint(int(dur * 0.85), dur)
            play_id += 1
            emit(f"INSERT INTO plays VALUES ({play_id}, {uid}, {t}, '{played_at:%Y-%m-%d %H:%M:%S}', {ms}, {skipped}, {q(random.choice(DEVICES))});")
            user_tracks.setdefault(uid, set()).add(t)
        day += timedelta(days=1)

# Playlists built from tracks each user actually played
playlist_id = 0
NAMES = ["vibes", "gym", "study", "road trip", "sad hours", "on repeat", "chill", "party", "morning", "late night"]
for uid, joined, *_ in users:
    for name in random.sample(NAMES, random.randint(1, 3)):
        playlist_id += 1
        created = joined + timedelta(days=random.randint(0, 300))
        emit(f"INSERT INTO playlists VALUES ({playlist_id}, {uid}, {q(name)}, {1 if random.random() < 0.7 else 0}, '{created}');")
        picks = random.sample(sorted(user_tracks.get(uid, [])), min(len(user_tracks.get(uid, [])), random.randint(8, 25)))
        for pos, t in enumerate(picks, 1):
            added = created + timedelta(days=random.randint(0, 200))
            emit(f"INSERT INTO playlist_tracks VALUES ({playlist_id}, {t}, {pos}, '{added}');")

emit("COMMIT;")
print("\n".join(out))
